from app.analytics.aggregator import aggregator
from app.api.dependencies import verify_application_api_key
from app.database.models.application import Application
from app.database.session import get_db
from app.schemas.analytics import CostAnalytics, ModelAnalytics, OverviewStats, SavingsAnalytics
from fastapi import APIRouter, Depends, Query
from sqlalchemy.ext.asyncio import AsyncSession

router = APIRouter(prefix="/analytics", tags=["Analytics & Reporting"])


@router.get("/overview", response_model=OverviewStats)
async def get_analytics_overview(
    days: int = Query(default=30, ge=1, le=365),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> OverviewStats:
    """Returns high-level operational statistics: requests, spend, savings, cache hit rate, and latency."""
    data = await aggregator.get_overview(db, organization_id=app.organization_id, days=days)
    return OverviewStats(**data)


@router.get("/costs", response_model=CostAnalytics)
async def get_analytics_costs(
    days: int = Query(default=14, ge=1, le=90),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> CostAnalytics:
    """Returns time-series daily spending, baseline costs, and cost savings."""
    data = await aggregator.get_costs(db, organization_id=app.organization_id, days=days)
    return CostAnalytics(**data)


