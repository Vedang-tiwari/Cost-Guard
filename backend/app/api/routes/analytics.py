from app.analytics.aggregator import aggregator
from app.api.dependencies import verify_application_api_key
from app.database.models.application import Application
from app.database.session import get_db
from app.schemas.analytics import (
    CostAnalytics,
    ModelAnalytics,
    OverviewStats,
    RequestLogItem,
    SavingsAnalytics,
)
from fastapi import APIRouter, Depends, Query
from sqlalchemy.ext.asyncio import AsyncSession

router = APIRouter(prefix="/analytics", tags=["Analytics & Reporting"])


@router.get("/overview", response_model=OverviewStats)
async def get_analytics_overview(
    days: int = Query(default=30, ge=1, le=365),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> OverviewStats:
    """Returns high-level operational statistics: requests, spend, savings, cache hit rate, quality, and latency."""
    data = await aggregator.get_overview(db, organization_id=app.organization_id, days=days)
    return OverviewStats(**data)


@router.get("/costs", response_model=CostAnalytics)
async def get_analytics_costs(
    days: int = Query(default=14, ge=1, le=365),
    period: str = Query(default="daily", pattern="^(daily|weekly|monthly)$"),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> CostAnalytics:
    """Returns time-series spending and cost breakdowns by provider, model, application, and token direction."""
    data = await aggregator.get_costs(db, organization_id=app.organization_id, days=days, period=period)
    return CostAnalytics(**data)


@router.get("/models", response_model=ModelAnalytics)
async def get_analytics_models(
    days: int = Query(default=30, ge=1, le=365),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> ModelAnalytics:
    """Returns breakdown of model usage, request counts, tokens, costs, quality scores, and latencies."""
    data = await aggregator.get_models(db, organization_id=app.organization_id, days=days)
    return ModelAnalytics(**data)


@router.get("/savings", response_model=SavingsAnalytics)
async def get_analytics_savings(
    days: int = Query(default=30, ge=1, le=365),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> SavingsAnalytics:
    """Returns breakdown of savings generated by caching, down-tier routing, and prompt compression."""
    data = await aggregator.get_savings(db, organization_id=app.organization_id, days=days)
    return SavingsAnalytics(**data)


@router.get("/logs", response_model=list[RequestLogItem])
async def get_recent_logs(
    limit: int = Query(default=50, ge=1, le=200),
    app: Application = Depends(verify_application_api_key),
    db: AsyncSession = Depends(get_db),
) -> list[RequestLogItem]:
    """Returns recent request logs with routing decisions, costs, savings, and quality telemetry."""
    rows = await aggregator.get_logs(db, organization_id=app.organization_id, limit=limit)
    return [RequestLogItem(**r) for r in rows]
